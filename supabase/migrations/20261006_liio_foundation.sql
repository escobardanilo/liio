create extension if not exists pgcrypto;

create table if not exists public.liio_families (
  id uuid primary key default gen_random_uuid(),
  owner_secret_hash text not null,
  parent_name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.liio_children (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.liio_families(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  age integer not null check (age between 6 and 15),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.liio_preferences (
  family_id uuid primary key references public.liio_families(id) on delete cascade,
  language text not null default 'en' check (language in ('pt','en','es','de')),
  updated_at timestamptz not null default now()
);

create table if not exists public.liio_pairing_codes (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.liio_families(id) on delete cascade,
  code_hash text not null unique,
  expires_at timestamptz not null,
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.liio_device_sessions (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.liio_families(id) on delete cascade,
  child_id uuid not null references public.liio_children(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null default (now() + interval '30 days'),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.liio_time_limits (
  child_id uuid primary key references public.liio_children(id) on delete cascade,
  daily_minutes integer not null default 60 check (daily_minutes between 15 and 180),
  quiet_start time not null default '20:00',
  quiet_end time not null default '07:00',
  homework_enabled boolean not null default true,
  voice_enabled boolean not null default true,
  create_world_enabled boolean not null default false,
  paused boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.liio_learning_sessions (
  id uuid primary key default gen_random_uuid(),
  child_id uuid not null references public.liio_children(id) on delete cascade,
  device_session_id uuid references public.liio_device_sessions(id) on delete set null,
  mode text not null default 'homework',
  language text not null default 'en' check (language in ('pt','en','es','de')),
  prompt_version text not null,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.liio_activity_events (
  id bigint generated by default as identity primary key,
  child_id uuid not null references public.liio_children(id) on delete cascade,
  learning_session_id uuid references public.liio_learning_sessions(id) on delete set null,
  event_type text not null,
  behavior text,
  duration_ms integer,
  success boolean,
  prompt_version text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

